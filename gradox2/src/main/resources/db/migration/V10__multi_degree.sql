-- V10: multi-grado. Introduce la tabla `degrees` y asigna un grado a todo lo existente.
--
-- Decisiones de referencia (Documentation/GRADOS.md):
--   D8  todos los usuarios, cursos y asignaturas existentes quedan en Ingeniería Informática.
--   D5  `vote_config` sigue siendo global: no se toca.
--   D13 `subjects` gana los metadatos del plan oficial (créditos, semestre, tipo).
--
-- La migración es ADITIVA sobre los datos existentes: no borra ni recrea filas. Las asignaturas
-- conservan su `id`, así que `files.subject_id` y `temp_files.subject_id` siguen apuntando a lo mismo
-- (el renombrado de códigos a los oficiales de la USC es la V11).
--
-- ⚠️ El backfill es irreversible: una vez aplicada, no se puede distinguir qué usuario llegó a qué
-- grado por su propia elección y qué usuario fue asignado por esta migración.

create table if not exists degrees (
    id bigint generated by default as identity,
    code varchar(16) not null unique,
    name varchar(255) not null,
    primary key (id)
);

insert into degrees (code, name) values
    ('G4012', 'Ingeniería Informática'),
    ('G4022', 'Ingeniería Química'),
    ('G4121', 'Inteligencia Artificial')
on conflict (code) do nothing;

-- ─────────────────────────────────────────────────────────────────────────────
-- users.degree_id: obligatorio. Todo lo que exista antes del multi-grado es Informática (D8).
-- ─────────────────────────────────────────────────────────────────────────────
alter table users add column if not exists degree_id bigint;
alter table users add constraint fk_users_degree foreign key (degree_id) references degrees (id);

update users
   set degree_id = (select id from degrees where code = 'G4012')
 where degree_id is null;

alter table users alter column degree_id set not null;
create index if not exists idx_users_degree on users (degree_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- courses.degree_id: el código de curso ('1'..'4') deja de ser único global y pasa a serlo por grado.
-- ─────────────────────────────────────────────────────────────────────────────
alter table courses add column if not exists degree_id bigint;
alter table courses add constraint fk_courses_degree foreign key (degree_id) references degrees (id);

update courses
   set degree_id = (select id from degrees where code = 'G4012')
 where degree_id is null;

alter table courses alter column degree_id set not null;
alter table courses drop constraint if exists courses_code_key;
alter table courses add constraint uk_courses_degree_code unique (degree_id, code);
create index if not exists idx_courses_degree on courses (degree_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- subjects: metadatos del plan oficial (D13). No se agrega `degree_id`: el grado de una asignatura
-- se deriva de su curso (§2.3), y su código oficial de la USC ya es único en toda la plataforma.
-- `credits` es double precision porque el plan publica asignaturas de 4,5 créditos.
-- `semester` queda nulo en las asignaturas anuales, que no tienen semestre.
-- ─────────────────────────────────────────────────────────────────────────────
alter table subjects add column if not exists credits double precision;
alter table subjects add column if not exists semester varchar(32);
alter table subjects add column if not exists subject_type varchar(64);
